const declarations = (entries) =>
  entries.map(([name, value]) => `  --${name}: ${value};`).join('\n');

const themed = (tokens, theme) =>
  [...tokens.color.tokens, ...tokens.shadow.tokens].map((token) => [
    token.name,
    token.value[theme] ?? token.value.papel,
  ]);

const typeStyles = (tokens) =>
  tokens.type.groups.flatMap((group) =>
    group.styles.flatMap((style) => {
      const font = `${style.fontStyle} ${style.fontWeight} ${style.fontSize}/${style.lineHeight} var(--font-${group.family})`;
      const entries = [[`type-${style.name}`, font]];
      if (style.letterSpacing) {
        entries.push([`type-${style.name}-tracking`, style.letterSpacing]);
      }
      return entries;
    }),
  );

const scale = (group) => group.tokens.map((token) => [token.name, token.value]);

const indent = (css) =>
  css
    .split('\n')
    .map((line) => `  ${line}`)
    .join('\n');

export function generateTokensCss(tokens) {
  const papel = declarations([
    ...themed(tokens, 'papel'),
    ...scale(tokens.spacing),
    ...scale(tokens.radius),
    ...typeStyles(tokens),
  ]);
  const grafite = declarations(themed(tokens, 'grafite'));

  return `/* Generated by scripts/generate-tokens.mjs from design-system/tokens.json. Do not edit. */

:root {
${papel}
}

[data-theme="grafite"] {
${grafite}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="papel"]) {
${indent(grafite)}
  }
}
`;
}
